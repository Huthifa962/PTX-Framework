#!/usr/bin/env python3
"""
build/generate.py
=================

Reads the taxonomy modules and (re)builds the PTX database on disk:

    database/paths.json         (with group + description)
    database/workflows.json     (per-domain roadmaps)
    database/methodology.json   (the universal PTES spine)
    database/aliases.json       (navigation shortcuts)
    database/<folder>/*.yaml     (one file per tool)

Run from the build/ directory:  python generate.py
It is idempotent: each managed domain folder is cleared and rewritten.
"""

from __future__ import annotations

import json
import re
import shutil
from pathlib import Path

import yaml

# Importing the domain modules triggers their register() calls.
import taxonomy
import d_crosscut  # noqa: F401
import d_core      # noqa: F401
import d_app       # noqa: F401
import d_infra     # noqa: F401
import d_hw        # noqa: F401
import d_emerging  # noqa: F401

_SLUG_RE = re.compile(r"[^a-z0-9]+")
DB = Path(__file__).resolve().parent.parent / "database"


def slugify(value: str) -> str:
    return _SLUG_RE.sub("-", value.strip().lower()).strip("-")


def write_json(path: Path, data) -> None:
    path.write_text(json.dumps(data, indent=2, ensure_ascii=False) + "\n", encoding="utf-8")


def build() -> None:
    domains = taxonomy.DOMAINS
    paths_out = []
    workflows_out = {}

    for index, domain in enumerate(domains):
        slug = slugify(domain["name"])
        folder = domain["folder"]
        paths_out.append({
            "name": domain["name"],
            "folder": folder,
            "group": domain.get("group", ""),
            "description": domain.get("description", ""),
        })
        workflows_out[slug] = [
            {"name": ph["name"], "description": ph.get("description", "")}
            for ph in domain["phases"]
        ]

        # Rewrite the domain's tool folder from scratch.
        folder_dir = DB / folder
        if folder_dir.exists():
            shutil.rmtree(folder_dir)
        folder_dir.mkdir(parents=True, exist_ok=True)

        seen: set[str] = set()
        for tool in domain["tools"]:
            fname = slugify(tool["name"]) or "tool"
            base = fname
            i = 2
            while fname in seen:
                fname = f"{base}-{i}"
                i += 1
            seen.add(fname)
            # Drop empty optional keys to keep YAML tidy.
            clean = {k: v for k, v in tool.items() if v not in ("", [], {}, None, False)}
            # Preserve explicit False for 'recommended' only if True; already dropped if False.
            (folder_dir / f"{fname}.yaml").write_text(
                "# Auto-generated by build/generate.py — edit the taxonomy, not this file.\n"
                + yaml.safe_dump(clean, sort_keys=False, allow_unicode=True, width=100),
                encoding="utf-8",
            )

    write_json(DB / "paths.json", paths_out)
    write_json(DB / "workflows.json", workflows_out)
    write_json(DB / "methodology.json", taxonomy.METHODOLOGY)

    # Navigation aliases (path + phase shortcuts).
    aliases = {
        "recon": "reconnaissance",
        "enum": "enumeration",
        "privesc": "privilege-escalation",
        "vuln": "vulnerability-assessment",
        "net": "network-penetration-testing",
        "web": "web-application",
        "ad": "active-directory",
        "core": "core-toolkit",
        "k8s": "container-kubernetes",
        "llm": "ai-llm-security",
        "ai": "ai-llm-security",
        "red": "red-team",
        "purple": "purple-team",
        "cloud": "cloud",
        "wifi": "wireless",
        "se": "social-engineering-physical",
    }
    write_json(DB / "aliases.json", aliases)

    tool_count = sum(len(d["tools"]) for d in domains)
    print(f"Generated {len(domains)} domains and {tool_count} tools.")
    groups = {}
    for d in domains:
        groups.setdefault(d.get("group", ""), 0)
        groups[d.get("group", "")] += 1
    for g, n in groups.items():
        print(f"  {g:<15} {n} domains")


if __name__ == "__main__":
    build()
